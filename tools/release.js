import {readFile,writeFile,mkdir,copyFile,readdir,unlink,realpath} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {RUNTIME_FILES,DELIVERY_FILES} from './runtime-files.js';
export const sha256=bytes=>createHash('sha256').update(bytes).digest('hex');
export async function releaseManifest(root){
  const assets=[];for(const url of RUNTIME_FILES)assets.push({url,sha256:sha256(await readFile(path.join(root,url)))});
  const version=sha256(JSON.stringify(assets)+sha256(await readFile(path.join(root,'sw.js')))).slice(0,20);
  return{version,assets};
}
export const configSource=manifest=>'// Generated by tools/release.js; update after changing interface files.\nself.STROIPLAN_RELEASE = '+JSON.stringify(manifest,null,2)+';\n';
export async function prepareRelease(root=process.cwd()){
  const manifest=await releaseManifest(root);await writeFile(path.join(root,'app-assets.js'),configSource(manifest));
  const target=path.resolve(root,'output/release/stroiplan');await mkdir(target,{recursive:true});
  const actualRoot=await realpath(root),actualTarget=await realpath(target);
  if(!actualTarget.startsWith(path.join(actualRoot,'output','release')+path.sep))throw Error('Release target outside output/release');
  async function prune(folder){for(const entry of await readdir(folder,{withFileTypes:true})){const file=path.join(folder,entry.name);if(entry.isDirectory())await prune(file);else{const relative=path.relative(target,file).replaceAll('\\','/');if(!DELIVERY_FILES.includes(relative))await unlink(file);}}}
  await prune(target);
  for(const file of DELIVERY_FILES){const dest=path.join(target,file);await mkdir(path.dirname(dest),{recursive:true});await copyFile(path.join(root,file),dest);}
  await writeFile(path.join(root,'output/release/verification.json'),JSON.stringify({...manifest,delivery:DELIVERY_FILES},null,2));
  console.log('Static release '+manifest.version+': '+DELIVERY_FILES.length+' files');return manifest;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))await prepareRelease();
